CREATE TABLE IF NOT EXISTS oauthAccounts (
  provider VARCHAR(16) NOT NULL,
  subject VARCHAR(255) NOT NULL,
  userId VARCHAR(128) NOT NULL,
  PRIMARY KEY (provider, subject),
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS sessions (
  tokenHash CHAR(64) PRIMARY KEY,
  userId VARCHAR(128) NOT NULL,
  provider VARCHAR(16) NOT NULL,
  authAt DATETIME(3) NOT NULL,
  expiresAt DATETIME(3) NOT NULL,
  INDEX (expiresAt),
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS oauthFlows (
  stateHash CHAR(64) PRIMARY KEY,
  browserHash CHAR(64) NOT NULL,
  provider VARCHAR(16) NOT NULL,
  mode VARCHAR(16) NOT NULL,
  userId VARCHAR(128),
  sessionHash CHAR(64),
  nonce VARCHAR(128),
  verifier VARCHAR(128),
  expiresAt DATETIME(3) NOT NULL,
  INDEX (expiresAt),
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS stories (
  id VARCHAR(128) PRIMARY KEY,
  parentId VARCHAR(128),
  rootId VARCHAR(128) NOT NULL,
  level SMALLINT UNSIGNED NOT NULL,
  authorId VARCHAR(128),
  status ENUM('active','draft','reported','deleted') NOT NULL,
  deletionSource VARCHAR(16),
  title VARCHAR(80) NOT NULL,
  deck VARCHAR(140) NOT NULL,
  genre VARCHAR(32) NOT NULL,
  body TEXT NOT NULL,
  views INT UNSIGNED NOT NULL DEFAULT 0,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX (updatedAt, id),
  INDEX (authorId, status, updatedAt),
  FOREIGN KEY (parentId) REFERENCES stories(id),
  FOREIGN KEY (authorId) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS storyArchives (
  storyId VARCHAR(128) PRIMARY KEY,
  title VARCHAR(80) NOT NULL,
  deck VARCHAR(140) NOT NULL,
  genre VARCHAR(32) NOT NULL,
  body TEXT NOT NULL,
  FOREIGN KEY (storyId) REFERENCES stories(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS comments (
  id VARCHAR(128) PRIMARY KEY,
  storyId VARCHAR(128) NOT NULL,
  parentCommentId VARCHAR(128),
  replyToCommentId VARCHAR(128),
  authorId VARCHAR(128),
  status ENUM('active','deleted') NOT NULL,
  deletionSource VARCHAR(16),
  text VARCHAR(600) NOT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX (storyId, createdAt, id),
  INDEX (storyId, status),
  FOREIGN KEY (storyId) REFERENCES stories(id) ON DELETE CASCADE,
  FOREIGN KEY (parentCommentId) REFERENCES comments(id) ON DELETE SET NULL,
  FOREIGN KEY (replyToCommentId) REFERENCES comments(id) ON DELETE SET NULL,
  FOREIGN KEY (authorId) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS storyLikes (
  storyId VARCHAR(128) NOT NULL,
  userId VARCHAR(128) NOT NULL,
  PRIMARY KEY (storyId, userId),
  FOREIGN KEY (storyId) REFERENCES stories(id) ON DELETE CASCADE,
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS commentLikes (
  commentId VARCHAR(128) NOT NULL,
  userId VARCHAR(128) NOT NULL,
  PRIMARY KEY (commentId, userId),
  FOREIGN KEY (commentId) REFERENCES comments(id) ON DELETE CASCADE,
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS reports (
  storyId VARCHAR(128) NOT NULL,
  userId VARCHAR(128) NOT NULL,
  PRIMARY KEY (storyId, userId),
  FOREIGN KEY (storyId) REFERENCES stories(id) ON DELETE CASCADE,
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS notifications (
  id VARCHAR(128) PRIMARY KEY,
  type VARCHAR(24) NOT NULL,
  actorId VARCHAR(128) NOT NULL,
  recipientId VARCHAR(128) NOT NULL,
  storyId VARCHAR(128) NOT NULL,
  targetStoryId VARCHAR(128) NOT NULL,
  `quote` VARCHAR(180) NOT NULL,
  readAt DATETIME(3),
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX (recipientId, createdAt, id),
  INDEX (recipientId, readAt),
  FOREIGN KEY (actorId) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (recipientId) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (storyId) REFERENCES stories(id) ON DELETE CASCADE,
  FOREIGN KEY (targetStoryId) REFERENCES stories(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS moderationAudit (
  id VARCHAR(128) PRIMARY KEY,
  action VARCHAR(32) NOT NULL,
  actorId VARCHAR(128),
  storyId VARCHAR(128) NOT NULL,
  previousStatus VARCHAR(16) NOT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX (createdAt, id),
  FOREIGN KEY (actorId) REFERENCES users(id) ON DELETE SET NULL,
  FOREIGN KEY (storyId) REFERENCES stories(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
